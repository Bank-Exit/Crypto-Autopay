<script>
  import { createEventDispatcher, onMount } from "svelte";
  import { invoke } from "@tauri-apps/api/core";
  import { t, currentLang, LANGUAGES } from "./i18n.js";
  import { theme, toggleTheme } from "./theme.js";

  const dispatch = createEventDispatcher();

  // mode: "new" | "restore"
  export let mode = "new";

  let step = mode === "restore" ? 2 : 1;

  // Step 1 — password
  let password = "";
  let passwordConfirm = "";
  let passwordError = "";

  // Step 2 — seed
  let seedMode = mode === "restore" ? "import" : "generate";
  let seedLoading = mode === "new";

  // Seed: generated by Rust backend, fallback for dev
  const FALLBACK_SEED = "abbey actor actress aged agree airport alien angry announce aquarium arena argue artist ascend august average awkward ball bamboo banana begin behind believe belong beset";
  let generatedSeed = FALLBACK_SEED;
  let importedSeed = "";

  // Step 3 — finalize wallet creation
  let finishLoading = false;
  let finishError = "";

  onMount(async () => {
    if (mode === "new") {
      try {
        generatedSeed = await invoke("generate_seed");
      } catch (e) {
        console.warn("generate_seed failed, using fallback:", e);
      }
      seedLoading = false;
    }
  });

  // Step 3 — backup + seed word verification
  let checkPaperSeed = false;
  let checkPaperPassword = false;
  let checkLimit = false;

  // Seed word challenge
  let verifyIndex = Math.floor(Math.random() * 25) + 1;  // 1-based, random
  let verifyInput = "";
  let verifyError = false;
  let verifyPassed = false;

  $: activeSeed = seedMode === "generate" ? generatedSeed : importedSeed;
  $: seedWords = activeSeed.trim().split(/\s+/);
  $: expectedWord = seedWords[verifyIndex - 1] || "";

  // Seed import validation
  $: importSeedError = (() => {
    if (!importedSeed) return null; // not touched yet
    const trimmed = importedSeed.trim();
    if (importedSeed !== trimmed) return "La seed ne doit pas commencer ni finir par un espace.";
    const words = trimmed.split(/\s+/);
    if (words.length !== 25) return `${words.length} mot(s) — il en faut exactement 25.`;
    if (/\s{2,}/.test(trimmed)) return "Un seul espace entre chaque mot.";
    return null; // valid
  })();
  $: importSeedValid = importedSeed.trim().split(/\s+/).length === 25
    && importedSeed === importedSeed.trim()
    && !/\s{2,}/.test(importedSeed.trim());

  function checkWord() {
    if (verifyInput.trim().toLowerCase() === expectedWord.toLowerCase()) {
      verifyPassed = true;
      checkPaperSeed = true;
      verifyError = false;
    } else {
      verifyError = true;
      verifyInput = "";
    }
  }

  function validateStep1() {
    passwordError = "";
    if (password.length < 12) { passwordError = $t.passwordTooShort; return false; }
    if (password !== passwordConfirm) { passwordError = $t.passwordMismatch; return false; }
    return true;
  }

  function goStep2() { if (validateStep1()) step = 2; }
  function goStep3() { step = 3; }

  async function finish() {
    finishLoading = true;
    finishError = "";
    try {
      await invoke("create_wallet", { seed: activeSeed, password });
      dispatch("complete");
    } catch (e) {
      finishError = typeof e === "string" ? e : JSON.stringify(e);
      finishLoading = false;
    }
  }

  function goBack() {
    if (step === 2 && mode === "restore") dispatch("back");
    else if (step === 2) step = 1;
    else if (step === 3) step = 2;
  }
</script>

<div class="onboarding">
  <!-- Progress bar -->
  <div class="progress-bar">
    <div class="progress-fill" style="width: {(step / 3) * 100}%"></div>
  </div>

  <!-- Top controls: lang + theme -->
  <div class="top-controls">
    <div class="lang-wrapper-sm">
      <svg class="globe-sm" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"
           stroke-linecap="round" stroke-linejoin="round">
        <circle cx="12" cy="12" r="10"/>
        <line x1="2" y1="12" x2="22" y2="12"/>
        <path d="M12 2a15.3 15.3 0 0 1 4 10 15.3 15.3 0 0 1-4 10 15.3 15.3 0 0 1-4-10 15.3 15.3 0 0 1 4-10z"/>
      </svg>
      <select bind:value={$currentLang} class="lang-select-sm">
        {#each LANGUAGES as lang}
          <option value={lang.code}>{lang.label}</option>
        {/each}
      </select>
    </div>
    <button class="theme-btn" on:click={toggleTheme}>
      {#if $theme === "light"}🌙{:else}☀️{/if}
    </button>
  </div>

  <div class="onboarding-inner">
    <!-- Header -->
    <div class="onb-header">
      <div class="onb-logo">
        <svg width="28" height="28" viewBox="0 0 72 72" fill="none">
          <path d="M36 8 A28 28 0 1 1 8 36" stroke="var(--accent)" stroke-width="5" stroke-linecap="round" fill="none"/>
          <polyline points="6,24 8,36 20,34" stroke="var(--accent)" stroke-width="5" stroke-linecap="round" stroke-linejoin="round" fill="none"/>
          <circle cx="24" cy="36" r="5" fill="var(--accent)" opacity="0.9"/>
          <circle cx="48" cy="36" r="5" fill="var(--accent)" opacity="0.5"/>
          <line x1="31" y1="36" x2="41" y2="36" stroke="var(--accent)" stroke-width="2.5" stroke-linecap="round"/>
          <polyline points="38,32 42,36 38,40" stroke="var(--accent)" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round" fill="none"/>
        </svg>
        <span class="onb-appname">Crypto AutoPay</span>
      </div>
      <div class="step-indicator">
        {$t.step} {step}/3 —
        {#if step === 1}{$t.stepPassword}
        {:else if step === 2}{$t.stepSeed}
        {:else}{$t.stepBackup}
        {/if}
      </div>
    </div>

    <!-- ======================== STEP 1: Password ======================== -->
    {#if step === 1}
      <div class="step-content card">
        <h2>{$t.stepPassword}</h2>
        <p class="step-desc text-muted">{$t.stepPasswordDesc}</p>

        <label>
          {$t.masterPassword}
          <input type="password" bind:value={password} placeholder={$t.masterPasswordPlaceholder} autocomplete="new-password" />
        </label>
        <label>
          {$t.confirmPassword}
          <input type="password" bind:value={passwordConfirm} placeholder={$t.confirmPasswordPlaceholder} autocomplete="new-password" />
        </label>

        {#if passwordError}
          <div class="error-msg">{passwordError}</div>
        {/if}

        <div class="warning-box">{$t.passwordWarning}</div>

        <button class="btn-primary btn-full" on:click={goStep2}>{$t.continue}</button>
      </div>
