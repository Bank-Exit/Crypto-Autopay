          </div>
        {:else}
          <p class="step-desc text-muted">{$t.stepSeedDesc}</p>
        {/if}

        <!-- 2 XMR security info -->
        <div class="info-box">
          <div class="info-box-title">🔒 {$t.seedLimit}</div>
          <p>{$t.seedLimitDetail}</p>
        </div>

        <!-- Seed mode toggle (hidden in restore) -->
        {#if mode !== "restore"}
          <div class="seed-choice">
            <button class="seed-option" class:selected={seedMode === "generate"} on:click={() => seedMode = "generate"}>
              <span class="seed-option-icon">✨</span>
              <div>
                <strong>{$t.generateSeed}</strong>
                <small>{$t.generateSeedHint}</small>
              </div>
            </button>
            <button class="seed-option" class:selected={seedMode === "import"} on:click={() => seedMode = "import"}>
              <span class="seed-option-icon">📥</span>
              <div>
                <strong>{$t.importSeed}</strong>
                <small>{$t.importSeedHint}</small>
              </div>
            </button>
          </div>
        {/if}

        {#if seedMode === "generate" && mode !== "restore"}
          <div class="seed-display">
            {#if seedLoading}
              <div class="seed-loading">
                <span class="spinner"></span>
                Génération de votre seed sécurisée…
              </div>
            {:else}
              <div class="seed-words">{generatedSeed}</div>
              <p class="seed-note">⚠ Notez ces 25 mots sur papier avant de continuer.</p>
            {/if}
          </div>
        {:else}
          <label>
            {$t.seedPhrase}
            <textarea
              bind:value={importedSeed}
              placeholder={$t.seedPhrasePlaceholder}
              rows="3"
              class:textarea-error={importedSeed && importSeedError}
              class:textarea-ok={importedSeed && !importSeedError}
              spellcheck="false"
              autocomplete="off"
              autocorrect="off"
            ></textarea>
          </label>
          {#if importedSeed && importSeedError}
            <div class="error-msg">{importSeedError}</div>
          {:else if importedSeed && importSeedValid}
            <div class="success-msg">✓ 25 mots valides</div>
          {/if}
        {/if}

        <button
          class="btn-primary btn-full"
          on:click={goStep3}
          disabled={seedMode === "import" && (!importSeedValid)}
        >{$t.continue}</button>
      </div>
    {/if}

    <!-- ======================== STEP 3: Backup + seed verification ======================== -->
    {#if step === 3}
      <div class="step-content card">
        <div class="step-header-row">
          <button class="btn-back" on:click={goBack}>← {$t.back}</button>
          <h2>{$t.stepBackup}</h2>
          <span></span>
        </div>

        <div class="checklist">
          <!-- Seed paper check: requires typing the right word to verify -->
          <div class="check-item-verify">
            {#if verifyPassed}
              <div class="verify-ok">
                <span class="verify-check">✓</span>
                <span>{$t.checkPaperSeed}</span>
                <span class="verify-proof text-muted">(mot n°{verifyIndex} : « {expectedWord} » ✓)</span>
              </div>
            {:else}
              <div class="verify-challenge">
                <p class="verify-prompt">
                  Pour confirmer que vous avez bien noté votre seed,
                  <strong>tapez le mot n°{verifyIndex}</strong> de votre phrase seed :
                </p>
                <div class="verify-input-row">
                  <input
                    bind:value={verifyInput}
                    placeholder="Mot #{verifyIndex}..."
                    on:keydown={e => e.key === "Enter" && checkWord()}
                    class:input-error={verifyError}
                    autocomplete="off"
                    spellcheck="false"
                  />
                  <button class="btn-primary" style="padding:9px 16px;font-size:13px" on:click={checkWord}>
                    Vérifier
                  </button>
                </div>
                {#if verifyError}
                  <p class="error-msg">Mot incorrect — réessayez.</p>
                {/if}
              </div>
            {/if}
          </div>

          <label class="check-item">
            <input type="checkbox" bind:checked={checkPaperPassword} />
            <span>{$t.checkPaperPassword}</span>
          </label>
          <label class="check-item">
            <input type="checkbox" bind:checked={checkLimit} />
            <span>{$t.checkLimit}</span>
          </label>
        </div>

        {#if finishError}
          <div class="error-msg">{finishError}</div>
        {/if}

        <button
          class="btn-primary btn-full"
          disabled={!verifyPassed || !checkPaperPassword || !checkLimit || finishLoading}
          on:click={finish}
        >
          {#if finishLoading}
            <span class="spinner"></span> Création du wallet…
          {:else}
            🚀 {$t.launchButton}
          {/if}
        </button>
      </div>
    {/if}
  </div>
</div>

